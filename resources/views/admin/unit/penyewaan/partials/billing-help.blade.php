<div id="billing-basis-help" class="bg-light rounded p-3 mb-3 small">
    <p class="mb-2"><strong>Sekali kegiatan (sekali pakai)</strong><br>
        Harga untuk satu unit alat selama satu kegiatan pada tanggal sewa yang dipesan. Harga tidak bertambah karena jumlah hari.
        Contoh: 1 unit sound system Rp700.000, dipakai tanggal 12–14 November untuk satu kegiatan, total tetap <strong>Rp700.000</strong>.
    </p>
    <p class="mb-2"><strong>Harian</strong><br>
        Harga untuk satu unit alat setiap hari. Tanggal mulai dan tanggal selesai sama-sama dihitung; sewa pada tanggal yang sama dihitung 1 hari.
        Contoh: 1 unit dengan tarif Rp700.000 per hari, dipakai tanggal 12–14 November = 3 hari, total <strong>Rp2.100.000</strong>.
    </p>
    <p class="mb-0 text-muted">Pada kedua pilihan, total juga dikalikan jumlah unit yang disewa. Tanggal sewa tetap wajib diisi untuk mengatur ketersediaan alat.</p>
</div>
